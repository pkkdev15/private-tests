# Bundles tests.json and every test file it lists into tests-data.js,
# so the app also works when index.html is opened straight from disk (file://),
# where browsers block fetch() of JSON files.
# Usage:  powershell -ExecutionPolicy Bypass -File build.ps1
# Re-run after editing any JSON file (serve.ps1 runs it automatically on start).

$root = $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)

$manifestText = [IO.File]::ReadAllText((Join-Path $root "tests.json"), $utf8)
$manifest = $manifestText | ConvertFrom-Json

$files = @()
foreach ($t in $manifest.tests) {
  $path = Join-Path $root $t.file
  if (-not (Test-Path $path -PathType Leaf)) { Write-Warning "Missing test file: $($t.file)"; continue }
  $json = [IO.File]::ReadAllText($path, $utf8)
  $null = $json | ConvertFrom-Json  # fail early on invalid JSON
  $key = $t.file | ConvertTo-Json
  $files += "    ${key}: $json"
}

$out = "// GENERATED by build.ps1 from tests.json and tests/*.json - do not edit by hand.`n" +
       "window.TEST_DATA = {`n  manifest: $manifestText,`n  files: {`n" + ($files -join ",`n") + "`n  }`n};`n"

[IO.File]::WriteAllText((Join-Path $root "tests-data.js"), $out, $utf8)
Write-Host "tests-data.js written ($($files.Count) tests)"

# Cache busting: stamp a new ?v= on CSS/JS links in index.html, so browsers
# fetch fresh files after a deploy instead of mixing old cached ones with new ones.
$indexPath = Join-Path $root "index.html"
$version = Get-Date -Format "yyyyMMddHHmm"
$index = [IO.File]::ReadAllText($indexPath, $utf8)
$stamped = [regex]::Replace($index, '(\.(?:css|js))\?v=\d+', "`$1?v=$version")
if ($stamped -ne $index) {
  [IO.File]::WriteAllText($indexPath, $stamped, $utf8)
  Write-Host "index.html assets stamped with ?v=$version"
}
